import { promises as fs } from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const toolsDir = path.join(projectRoot, "src", "tools");
const outputFile = path.join(
  projectRoot,
  "src",
  "lib",
  "tool-registry.generated.ts",
);

async function getToolFolders() {
  try {
    const entries = await fs.readdir(toolsDir, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();
  } catch {
    return [];
  }
}

function buildRegistryContent(folders) {
  const imports = folders.map(
    (folder, index) =>
      `import { manifest as toolManifest${index} } from "@/tools/${folder}/manifest";`,
  );

  const manifests = folders.map((_, index) => `  toolManifest${index},`);

  const header = [
    "// This file is auto-generated by scripts/generate-tool-registry.mjs.",
    "// Do not edit this file manually.",
    'import type { ToolManifest } from "@/lib/tool-manifest";',
    "",
  ];

  if (folders.length === 0) {
    return [
      ...header,
      "export const registeredToolManifests: ToolManifest[] = [];",
      "",
    ].join("\n");
  }

  return [
    ...header,
    ...imports,
    "",
    "export const registeredToolManifests: ToolManifest[] = [",
    ...manifests,
    "];",
    "",
  ].join("\n");
}

async function main() {
  const folders = await getToolFolders();
  const content = buildRegistryContent(folders);
  await fs.writeFile(outputFile, content, "utf8");
  console.log(`Generated registry for ${folders.length} tool(s).`);
}

main().catch((error) => {
  console.error("Failed to generate tool registry:", error);
  process.exit(1);
});
